function choices(rng: Rng, answer: string, candidates: string[]): string[] {
  const wrong = shuffle(rng, [...new Set(candidates)].filter((c) => c !== answer)).slice(0, 3);
  return shuffle(rng, [answer, ...wrong]);
}

